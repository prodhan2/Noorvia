/// Noorvia's lightweight runtime localization layer.
///
/// Bangla remains the canonical source language so the existing app keeps its
/// natural Bangla wording. English translations are kept centrally here. This
/// also lets remote/API text remain untouched (especially verified Quran text).
class AppI18n {
  AppI18n._();

  // Context-free fallback for InputDecoration/tooltips created outside build().
  // AppLanguageProvider keeps this synchronized before rebuilding MaterialApp.
  static String _currentLanguageCode = 'bn';

  static void setCurrentLanguageCode(String code) {
    _currentLanguageCode = code == 'en' ? 'en' : 'bn';
  }

  static String current(String source) =>
      _currentLanguageCode == 'en' ? toEnglish(source) : source;

  static bool isEnglish(BuildContext context) =>
      Localizations.localeOf(context).languageCode == 'en';

  static String tr(BuildContext context, String source) =>
      isEnglish(context) ? toEnglish(source) : source;

  static String toEnglish(String source) {
    if (source.trim().isEmpty) return source;
    final exact = _exact[source];
    if (exact != null) return exact;

    var out = source;
    for (final entry in _phrases) {
      out = _replaceBanglaPhrase(out, entry.$1, entry.$2);
    }
    out = _bnDigitsToEn(out);

    // Never show a broken half-Bangla/half-English sentence. Long rich
    // content (Ruqyah articles, Dua text, legacy Quran translations, etc.)
    // stays in its original language until an explicit verified translation
    // is available. High-visibility UI strings are translated by _exact.
    return _containsBangla(out) ? source : out;
  }

  static String _replaceBanglaPhrase(String input, String from, String to) {
    if (from.isEmpty || !input.contains(from)) return input;
    var out = input;
    var fromIndex = 0;
    final leftNeedsBoundary = _isBanglaCodeUnit(from.codeUnitAt(0));
    final rightNeedsBoundary = _isBanglaCodeUnit(from.codeUnitAt(from.length - 1));

    while (true) {
      final index = out.indexOf(from, fromIndex);
      if (index < 0) break;
      final end = index + from.length;
      final leftOk = !leftNeedsBoundary || index == 0 || !_isBanglaCodeUnit(out.codeUnitAt(index - 1));
      final rightOk = !rightNeedsBoundary || end == out.length || !_isBanglaCodeUnit(out.codeUnitAt(end));
      if (leftOk && rightOk) {
        out = out.replaceRange(index, end, to);
        fromIndex = index + to.length;
      } else {
        fromIndex = end;
      }
    }
    return out;
  }

  static bool _isBanglaCodeUnit(int codeUnit) => codeUnit >= 0x0980 && codeUnit <= 0x09FF;

  static bool _containsBangla(String text) =>
      text.codeUnits.any(_isBanglaCodeUnit);

  static String _bnDigitsToEn(String text) {
    const bn = '০১২৩৪৫৬৭৮৯';
    const en = '0123456789';
    var result = text;
    for (var i = 0; i < bn.length; i++) {
      result = result.replaceAll(bn[i], en[i]);
    }
    return result;
  }

